'use strict';

function semanticNode({
  nodeId,
  sourceIndex,
  rawTreeId,
  screenshotId = null,
  role,
  text = null,
  label = null,
  textTruncated,
  labelTruncated,
  hint,
  errorText,
  context,
  bounds = null,
  enabled = true,
  checked = null,
  selected = null,
  clickable = false,
  resourceName,
  editable,
  interaction,
  visible,
  effectiveVisible,
  accessibilityId,
  elementId,
  elementType,
  targetRef,
}) {
  return {
    nodeId: String(nodeId),
    sourceIndex,
    rawTreeId,
    screenshotId,
    role,
    text,
    label,
    ...(textTruncated === true ? { textTruncated: true } : {}),
    ...(labelTruncated === true ? { labelTruncated: true } : {}),
    bounds,
    enabled,
    checked,
    selected,
    clickable,
    ...(typeof hint === 'string' ? { hint } : {}),
    ...(typeof errorText === 'string' ? { errorText } : {}),
    ...(context === undefined ? {} : { context }),
    ...(typeof resourceName === 'string' ? { resourceName } : {}),
    ...(typeof editable === 'boolean' ? { editable } : {}),
    ...(interaction === undefined ? {} : { interaction }),
    ...(typeof visible === 'boolean' ? { visible } : {}),
    ...(typeof effectiveVisible === 'boolean' ? { effectiveVisible } : {}),
    ...(typeof accessibilityId === 'string' ? { accessibilityId } : {}),
    ...(typeof elementId === 'string' ? { elementId } : {}),
    ...(typeof elementType === 'string' ? { elementType } : {}),
    ...(targetRef === undefined ? {} : { targetRef }),
  };
}

module.exports = { semanticNode };
